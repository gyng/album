import { formatAspectRatio } from "./formatAspectRatio";

describe("formatAspectRatio", () => {
  it.each([
    [6000, 4000, "3:2"],
    [4000, 6000, "2:3"],
    [3200, 3200, "1:1"],
    [1920, 1080, "16:9"],
    [4432, 2955, "3:2"],
    [2955, 4432, "2:3"],
    [4031, 3024, "4:3"],
    [3024, 4031, "3:4"],
    [4080, 3072, "4:3"],
    [3072, 4080, "3:4"],
    [1919, 1080, "16:9"],
    [5995, 4000, "3:2"],
    [5980, 4000, "3:2"],
    [5940, 4000, "≈1.485:1"],
    [4000, 5940, "≈1:1.485"],
    [4500, 3200, "7:5"],
    [4570, 3200, "≈1.428:1"],
    [2000, 1300, "20:13"],
    [0, 4000, "—"],
    [6000, Number.NaN, "—"],
  ])("formats %i × %i as %s", (width, height, expected) => {
    expect(formatAspectRatio(width, height)).toBe(expected);
  });
});
